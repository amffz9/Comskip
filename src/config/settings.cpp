template<std::size_t N> void copy_string(const comskip::config::Ini& ini, const char* key, char (&target)[N]) {
    const auto* value = ini.find(key);
    if (!value) return;
    if (value->size() >= N) throw std::invalid_argument(std::string(key) + " is too long");
    std::memcpy(target, value->c_str(), value->size() + 1);
}
