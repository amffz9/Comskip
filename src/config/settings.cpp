    auto number = [&]<class T>(const char* key, T& target, int sign = 1) {
        if (!ini.find(key)) return;
        T value = ini.number<T>(key);
        if ((std::string_view(key) == "thread_count" || std::string_view(key) == "num_logo_buffers" ||
             std::string_view(key) == "fps" || std::string_view(key) == "edge_radius" ||
             std::string_view(key) == "edge_step") && value <= 0)
            throw std::invalid_argument(std::string(key) + " must be positive");
        if (sign == -1) {
            if (value == std::numeric_limits<T>::lowest()) throw std::invalid_argument("Audio delay out of range");
            value = static_cast<T>(-value);
        }
        updates.emplace_back([&target, value] { target = value; });
    };
    auto text = [&]<std::size_t N>(const char* key, char (&target)[N]) {
        const auto* value = ini.find(key);
        if (!value) return;
        if (value->size() >= N) throw std::invalid_argument(std::string(key) + " is too long");
        if (std::string_view(key) == "windowtitle") {
            int placeholders = 0;
            for (std::size_t i = 0; i < value->size(); ++i) {
                if ((*value)[i] != '%') continue;
                if (++i == value->size() || ((*value)[i] != '%' && (*value)[i] != 's'))
                    throw std::invalid_argument("windowtitle accepts only %s and %%");
                if ((*value)[i] == 's' && ++placeholders > 1)
                    throw std::invalid_argument("windowtitle accepts at most one filename placeholder");
            }
        }
        updates.emplace_back([&target, value = *value] { std::memcpy(target, value.c_str(), value.size() + 1); });
    };
